const SLUG_SCENE = new Map<string, Scene>(
  (Object.entries(BY_SLUG) as [Scene, string][]).flatMap(([scene, slugs]) => slugs.split(" ").map((s) => [s, scene] as const)),
);

// Własne ćwiczenia: zgadujemy po nazwie (kolejność ma znaczenie: „wyciskanie leżąc” przed „wyciskaniem”).
const BY_NAME: [RegExp, Scene][] = [
  [/rozpięt|butterfly|krzyżow/i, "fly"],
  [/le[żz][aą]c|ławk|klat/i, "bench"],
  [/nad głow|żołnier|barki|wyciskanie/i, "overhead"],
  [/wznos|bokiem/i, "lateral"],
  [/martw|rdl|skłon/i, "deadlift"],
  [/hip ?thrust|most|pośladk/i, "hipthrust"],
  [/przysiad|squat/i, "squat"],
  [/wykrok|zakrok|bułgar|wejści/i, "lunge"],
  [/podciąg|drąż|zwis/i, "pullup"],
  [/poręcz|dip/i, "dip"],
  [/wiosł|row/i, "row"],
  [/ugin|biceps|curl|młotk/i, "curl"],
  [/wyciąg|lin[kc]|ściąg/i, "cable"],
  [/desk|plank|brzuch|pomp|spięc/i, "plank"],
  [/kettl|odważ/i, "kettlebell"],
  [/spacer|farmer|nosz/i, "carry"],
  [/bieg|rower|wiośl|orbit|skakank|schod/i, "cardio"],
  [/maszyn|nóg|nogi|łyd/i, "legmachine"],
];

export function sceneFor(e: { slug?: string | null; name: string; equipment?: string; tracking?: string }): Scene {
  const bySlug = e.slug ? SLUG_SCENE.get(e.slug) : undefined;
  if (bySlug) return bySlug;
  const byName = BY_NAME.find(([re]) => re.test(e.name))?.[1];
  if (byName) return byName;
  if (e.tracking === "duration" || e.tracking === "distance") return "cardio";
  if (e.equipment === "Wyciąg") return "cable";
  if (e.equipment === "Maszyna") return "legmachine";
  return "carry";
}

const SCENE_PALETTE: Record<string, string> = { ...PALETTE, B: "#3c5047", F: "#1d2b24" };

/** Obrazek ćwiczenia; szerokość w px, wysokość wynika z proporcji 3:2. */
export function ExerciseArt({
  exercise,
  size = 72,
  className = "",
}: {
  exercise: { slug?: string | null; name: string; equipment?: string; tracking?: string };
  size?: number;
  className?: string;
}) {
  const rows = SCENES[sceneFor(exercise)];
  return (
    <svg
      viewBox="-1 -1 26 18"
      width={size}
      height={(size * 18) / 26}
      shapeRendering="crispEdges"
      className={`shrink-0 rounded-lg bg-surface-2/80 ${className}`}
      aria-hidden
    >
      {rows.flatMap((line, y) =>
        [...line].flatMap((c, x) => (c === "." ? [] : [<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={SCENE_PALETTE[c]} />])),
      )}
    </svg>
  );
}
