export type PixelIconName = keyof typeof ICONS;
export const hasPixelIcon = (name: string): name is PixelIconName => name in ICONS;

export function PixelIcon({ name, size = 22, accent = "var(--color-amber)", className = "" }: { name: PixelIconName; size?: number; accent?: string; className?: string }) {
  const rows = ICONS[name];
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" className={className} aria-hidden>
      {rows.flatMap((line, y) =>
        [...line].flatMap((c, x) =>
          c === "." ? [] : [<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={c === "o" ? accent : "currentColor"} />],
        ),
      )}
    </svg>
  );
}
